// Control structures - conditionals
const isTrue = true;
const isFalse = false;

console.log('IF ELSE statement with false condition');
if (isFalse) {
    console.log('Condition is true');
} else {
    console.log('Condition is false');
}

console.log('IF ELSE statement with true condition');
if (isTrue) {
    console.log('Condition is true');
} else {
    console.log('Condition is false');
}